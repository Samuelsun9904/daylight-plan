import json
from browser_qa import target,wait,click,assert_js

c=target('http://127.0.0.1:8766/daylight-plan/')
c.call('Page.enable');c.call('Network.enable')
wait(c,"!!document.querySelector('#list-eyebrow')?.textContent")
if c.evaluate("document.querySelector('#install-dialog').open"):click(c,'[data-action="close-install"]')
click(c,'[data-action="new"]')
c.evaluate("document.querySelector('#task-title').value='贝尔口解第一讲'")
for title in ['第一讲1','第一讲2']:
    click(c,'[data-action="add-subtask"]')
    c.evaluate(f"(()=>{{const input=document.querySelector('.subtask-row:last-child .subtask-title');input.value={json.dumps(title)};input.dispatchEvent(new Event('input',{{bubbles:true}}))}})()")
click(c,'.subtask-checkbox')
c.evaluate("(()=>{const input=document.querySelector('[data-subtask-time]');input.value='2026-10-17T12:12';input.dispatchEvent(new Event('change',{bubbles:true}))})()")
assert_js(c,"document.querySelector('#subtask-progress').textContent==='1/2'",'draft progress counts completed children')
c.evaluate("document.querySelector('#task-form').requestSubmit()")
wait(c,"!document.querySelector('#task-dialog').open")
id=c.evaluate("[...document.querySelectorAll('.task-card')].find(e=>e.textContent.includes('贝尔口解第一讲')).dataset.taskId")
click(c,f'[data-edit="{id}"]')
assert_js(c,"document.querySelector('[data-subtask-time]').value==='2026-10-17T12:12'",'historical completion time survives save and edit')
click(c,'[data-action="add-subtask"]');c.evaluate("document.querySelector('.subtask-row:last-child .subtask-title').value='不保存的子任务';document.querySelector('.subtask-row:last-child .subtask-title').dispatchEvent(new Event('input',{bubbles:true}))")
click(c,'[data-action="close-editor"]');click(c,f'[data-edit="{id}"]')
assert_js(c,"document.querySelectorAll('.subtask-row').length===2",'cancel does not modify saved children')
click(c,'[data-action="close-editor"]')
click(c,f'[data-task-id="{id}"] summary')
child=c.evaluate(f"document.querySelector('[data-task-id=\"{id}\"] [data-subtask-toggle]').dataset.subtaskToggle")
# Complete the second child directly from the home card.
c.evaluate(f"[...document.querySelectorAll('[data-task-id=\"{id}\"] [data-subtask-toggle]')][1].click()")
assert_js(c,f"document.querySelector('[data-task-id=\"{id}\"]').classList.contains('completed')",'all child completion marks parent completed')
assert_js(c,f"document.querySelector('[data-task-id=\"{id}\"] details').open",'expanded children remain open after checking')
click(c,f'[data-edit="{id}"]')
c.call('Emulation.setDeviceMetricsOverride',{'width':390,'height':844,'deviceScaleFactor':1,'mobile':True})
c.evaluate("document.querySelector('#task-dialog').scrollTop=document.querySelector('.subtask-editor').offsetTop-40")
c.shot('phone-subtasks.png')
click(c,'[data-action="close-editor"]')
click(c,f'[data-toggle="{id}"]')
assert_js(c,f"[...document.querySelectorAll('[data-task-id=\"{id}\"] [data-subtask-toggle]')].every(e=>e.getAttribute('aria-pressed')==='false')",'undo parent clears child completion')
c.call('Network.emulateNetworkConditions',{'offline':True,'latency':0,'downloadThroughput':0,'uploadThroughput':0})
c.call('Page.reload')
wait(c,f"!!document.querySelector('[data-task-id=\"{id}\"] .subtask-badge')")
assert_js(c,f"document.querySelector('[data-task-id=\"{id}\"] .subtask-badge').textContent.includes('0/2')",'subtasks persist through offline relaunch')
print('Subtask UI checks passed')
